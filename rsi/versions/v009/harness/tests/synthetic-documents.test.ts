import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { describe, expect, it } from 'vitest';
import cases from '../src/data/documents/cases.json';
import manifest from '../src/data/documents/manifest.json';
import oracles from './documents/oracles.json';

describe('frozen synthetic document artifacts (not OCR evaluation)', () => {
  it('preserves the generated bytes, formats and page counts', () => {
    expect(manifest.filter(item => item.format === 'pdf')).toHaveLength(6);
    expect(manifest.filter(item => item.format === 'png')).toHaveLength(24);
    expect(manifest.filter(item => item.format === 'pdf').reduce((n, item) => n + item.pageCount, 0)).toBe(24);
    for (const item of manifest) {
      const data = readFileSync(item.path);
      expect(createHash('sha256').update(data).digest('hex')).toBe(item.sha256);
      expect(data.subarray(0, item.format === 'pdf' ? 4 : 8).toString(item.format === 'pdf' ? 'ascii' : 'hex'))
        .toBe(item.format === 'pdf' ? '%PDF' : '89504e470d0a1a0a');
      expect(item.generationMode).toBe('local_deterministic');
    }
  });

  it('keeps synthetic cases disjoint and does not supply ground truth in document inputs', () => {
    expect(new Set(cases.map(item => item.caseId)).size).toBe(6);
    expect(new Set(cases.map(item => item.suite))).toEqual(new Set(['discovery', 'validation', 'holdout']));
    for (const item of cases) {
      expect(item.synthetic).toBe(true);
      expect(item.creditBureauConsent).toBe(false);
      expect(item).not.toHaveProperty('expectedFindingCodes');
      expect(oracles.find(oracle => oracle.caseId === item.caseId)?.suite).toBe(item.suite);
    }
    expect(oracles.find(item => item.caseId === 'doc-holdout-income-missing')?.fields)
      .toContainEqual(expect.objectContaining({ fieldName: 'Ingreso mensual', value: null, state: 'absent' }));
    expect(oracles.find(item => item.caseId === 'doc-holdout-income-conflict')?.contradictions).toHaveLength(1);
  });
});
